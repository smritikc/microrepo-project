import { SecretFinding } from "@shield/types";

/**
 * Automatically creates a secure .env.example template based on detected secret types.
 */
export function generateEnvExample(findings: SecretFinding[]): string {
  const envVars = new Set<string>();

  for (const finding of findings) {
    if (finding.ruleId === "RULE_AWS_KEY") {
      envVars.add("AWS_ACCESS_KEY_ID=your_aws_access_key_id");
      envVars.add("AWS_SECRET_ACCESS_KEY=your_aws_secret_access_key");
    } else if (finding.ruleId === "RULE_OPENAI_KEY") {
      envVars.add("OPENAI_API_KEY=sk-your_openai_api_key");
    } else if (finding.ruleId === "RULE_GITHUB_TOKEN") {
      envVars.add("GITHUB_TOKEN=ghp_your_github_personal_access_token");
    } else if (finding.ruleId === "RULE_STRIPE_KEY") {
      envVars.add("STRIPE_SECRET_KEY=sk_live_your_stripe_secret_key");
    } else {
      envVars.add(`SECRET_TOKEN_${finding.id.toUpperCase()}=your_secret_token_here`);
    }
  }

  return `# Generated by SecretShield Remediation Engine
# Replace these placeholder values with actual secrets in your local .env file

${Array.from(envVars).join("\n")}
`;
}
